import { writeFile } from 'node:fs/promises';
import { test, expect } from './pdf-browser';
import { longPdfTranslation, pdfLayoutFixture, pdfLayoutProbes, pdfLayoutTexts } from './pdf-layout-fixture';

test('彩底报告逐块显示真实译文，数字、邮箱与后绘表格线保持原像素，原文切换可完全恢复', async ({ pdf }, testInfo) => {
  const { driver, server } = pdf;
  const started = performance.now();
  await driver.command('fill', ['#pdf-url', `${server.url}/pdf-layout-fixture.pdf`]);
  await driver.command('click', ['打开']);
  await expect.poll(async () => (await driver.snapshot()).canvasVisible).toBe(true);
  const firstPaintMs = performance.now() - started;
  await expect.poll(async () => (await driver.snapshot()).source).toContain(pdfLayoutTexts.body);
  let state = await driver.snapshot();
  expect(state.name).toContain('4 页'); expect(state.mode).toBe('layout'); expect(state.reading).toBe(false);
  expect(state.canvases).toBe(3); expect(state.pixels).toBeLessThanOrEqual(6000000);
  expect(state.reader.scrollWidth).toBeLessThanOrEqual(state.reader.clientWidth + 1);
  const before = await driver.pixels(pdfLayoutProbes);
  expect(before.changed).toBe(0); expect(before.nonWhite).toBeGreaterThan(1000); expect(server.calls).toHaveLength(0);

  server.holdStreams(); const translationStarted = performance.now();
  await driver.command('click', ['开启双语']);
  await expect.poll(async () => (await driver.snapshot()).overlays.filter(block => block.translated && block.visible).length).toBe(1);
  const firstOverlayMs = performance.now() - translationStarted;
  state = await driver.snapshot(); expect(state.status).toContain('正在翻译');
  expect(state.translations.join('')).toContain('云朵观测站');
  const partial = await driver.pixels(pdfLayoutProbes);
  expect(partial.changed).toBeGreaterThan(0); expect(partial.outsideOverlays).toBe(0);
  expect(partial.probes.find(probe => probe.name === 'body-text')!.changed).toBe(0);
  server.releaseStreams();
  await expect.poll(async () => (await driver.snapshot()).status).toContain('本页翻译完成');
  state = await driver.snapshot();
  expect(state.overlays.filter(block => block.translated)).toHaveLength(9);
  expect(state.overlays.every(block => block.inside && block.fitted)).toBe(true);
  const after = await driver.pixels(pdfLayoutProbes);
  expect(after.originalHash).toBe(before.originalHash); expect(after.changed).toBeGreaterThan(partial.changed); expect(after.outsideOverlays).toBe(0);
  for (const probe of after.probes.filter(probe => probe.name !== 'body-text')) expect(probe.changed, probe.name).toBe(0);
  expect(after.probes.find(probe => probe.name === 'body-text')!.changed).toBeGreaterThan(0);
  for (const name of ['numeric-readings', 'numeric-quality', 'email']) expect(after.probes.find(probe => probe.name === name)!.backgroundDifference, name).toBeGreaterThan(0);
  const requested = server.calls.flatMap(call => call.texts ?? []);
  for (const value of ['128', '256', '97.5%', '99.0%', 'reader@example.test']) expect(requested).not.toContain(value);
  expect(requested.join(' ')).not.toContain('reader@example.test');
  expect(requested).toContain('North Meadow'); expect(requested).toContain('OBSERVATORY');

  await driver.command('click', ['显示原文']);
  await expect.poll(async () => (await driver.pixels()).changed).toBe(0);
  expect((await driver.snapshot()).overlays).toHaveLength(0);
  expect((await driver.pixels()).originalHash).toBe(before.originalHash);
  await driver.command('click', ['显示译文']);
  await expect.poll(async () => (await driver.snapshot()).overlays.filter(block => block.translated).length).toBe(9);
  const requestsBeforeZoom = server.calls.length;
  await driver.command('click', ['100%']); await expect.poll(async () => (await driver.snapshot()).zoom).toBe(100);
  await driver.command('click', ['适合宽度']);
  await expect.poll(async () => { const current = await driver.snapshot(); return current.reader.scrollWidth <= current.reader.clientWidth + 1 && current.canvasVisible; }).toBe(true);
  const requestsAfterZoom = server.calls.length; expect(requestsAfterZoom).toBe(requestsBeforeZoom);
  const screenshot = testInfo.outputPath('pdf-report-layout.png'); const screenshotCaptured = await driver.screenshot(screenshot);
  state = await driver.snapshot();
  const report = testInfo.outputPath('pdf-layout-measurements.json');
  await writeFile(report, JSON.stringify({ environment: 'local mock model; observed front-end readiness, not model TPS', firstPaintMs, firstOverlayMs,
    canvasPixels: state.pixels, requestsBeforeZoom, requestsAfterZoom, screenshot: screenshotCaptured ? screenshot : null, screenshotCaptured, originalHash: before.originalHash,
    translatedPixels: after.changed, outsideOverlayChanges: after.outsideOverlays, probes: after.probes }, null, 2));
  await testInfo.attach('pdf-layout-measurements.json', { path: report, contentType: 'application/json' });
});

test('长译文可用键盘展开读完，缩放与模式切换保留阅读位置，手机单页无横向溢出且不重复请求', async ({ pdf }, testInfo) => {
  const { driver, server } = pdf;
  await driver.command('file', [pdfLayoutFixture.toString('base64'), 'fictional-observatory.pdf']);
  await expect.poll(async () => (await driver.snapshot()).source).toContain(pdfLayoutTexts.note);
  await driver.command('click', ['开启双语']);
  await expect.poll(async () => (await driver.snapshot()).status).toContain('本页翻译完成');
  let state = await driver.snapshot(); const note = state.source.indexOf(pdfLayoutTexts.note);
  expect(note).toBeGreaterThanOrEqual(0);
  expect(state.overlays.find(block => block.index === note)).toMatchObject({ translated: true, overflow: true, inside: true, fitted: true });
  await driver.command('open-block', [String(note), 'Enter']);
  await expect.poll(async () => (await driver.snapshot()).dialog.open).toBe(true);
  state = await driver.snapshot(); expect(state.dialog.source).toBe(pdfLayoutTexts.note); expect(state.dialog.translation).toBe(longPdfTranslation);
  await driver.command('dialog-scroll', ['100000']);
  await expect.poll(async () => (await driver.snapshot()).dialog.scrollTop).toBeGreaterThan(0);
  state = await driver.snapshot(); expect(state.dialog.closeVisible).toBe(true); expect(state.dialog.closeHit).toBe(true);
  await driver.screenshot(testInfo.outputPath('pdf-long-detail-desktop.png'));
  await driver.command('escape'); await expect.poll(async () => (await driver.snapshot()).dialog.open).toBe(false);
  expect((await driver.snapshot()).focusedBlock).toBe(String(note));

  const requestsBeforeZoom = server.calls.length;
  await driver.command('click', ['100%']); await expect.poll(async () => (await driver.snapshot()).zoom).toBe(100);
  await driver.command('scroll', ['160', '80']); await driver.command('frame');
  const layoutScroll = (await driver.snapshot()).reader.scrollTop; expect(layoutScroll).toBeGreaterThan(0);
  await driver.command('click', ['阅读模式']); await expect.poll(async () => (await driver.snapshot()).reading).toBe(true);
  expect((await driver.snapshot()).translations).toContain(longPdfTranslation);
  await driver.command('scroll', ['230']); await driver.command('frame');
  const readingScroll = (await driver.snapshot()).reader.scrollTop; expect(readingScroll).toBeGreaterThan(0);
  await driver.command('click', ['页面对照']);
  await expect.poll(async () => Math.abs((await driver.snapshot()).reader.scrollTop - layoutScroll)).toBeLessThanOrEqual(2);
  await driver.command('click', ['阅读模式']);
  await expect.poll(async () => Math.abs((await driver.snapshot()).reader.scrollTop - readingScroll)).toBeLessThanOrEqual(2);
  await driver.command('click', ['页面对照']);
  await driver.viewport(390, 640); await expect.poll(async () => (await driver.snapshot()).width).toBe(390);
  await driver.command('click', ['适合宽度']);
  await expect.poll(async () => { const current = await driver.snapshot(); return current.canvasVisible && current.reader.scrollWidth <= current.reader.clientWidth + 1; }).toBe(true);
  state = await driver.snapshot(); expect(state.overflow).toBe(false); expect(state.canvasDetails.filter(canvas => canvas.visible)).toHaveLength(1);
  expect(state.canvases).toBe(3); expect(state.pixels).toBeLessThanOrEqual(6000000);
  expect(state.overlays.every(block => block.inside && block.fitted)).toBe(true);
  await driver.command('open-block', [String(note)]); await expect.poll(async () => (await driver.snapshot()).dialog.open).toBe(true);
  await driver.command('dialog-scroll', ['100000']);
  await expect.poll(async () => (await driver.snapshot()).dialog.scrollTop).toBeGreaterThan(0);
  state = await driver.snapshot(); expect(state.dialog.translation).toBe(longPdfTranslation);
  expect(state.dialog.box.x).toBeGreaterThanOrEqual(12); expect(state.dialog.box.x + state.dialog.box.width).toBeLessThanOrEqual(378);
  expect(state.dialog.box.y).toBeGreaterThanOrEqual(8); expect(state.dialog.box.y + state.dialog.box.height).toBeLessThanOrEqual(632);
  expect(state.dialog.closeVisible).toBe(true); expect(state.dialog.closeHit).toBe(true);
  await driver.screenshot(testInfo.outputPath('pdf-long-detail-mobile.png'));
  await driver.command('click', ['关闭段落详情']); await expect.poll(async () => (await driver.snapshot()).dialog.open).toBe(false);
  const requestsAfterZoom = server.calls.length; expect(requestsAfterZoom).toBe(requestsBeforeZoom);
  await driver.command('scroll', ['0', '0']); await driver.screenshot(testInfo.outputPath('pdf-report-mobile.png'));
  const report = testInfo.outputPath('pdf-interaction-measurements.json');
  await writeFile(report, JSON.stringify({ requestsBeforeZoom, requestsAfterZoom, canvasPixels: state.pixels, layoutScroll, readingScroll,
    mobileDialog: state.dialog, screenshots: ['pdf-long-detail-desktop.png', 'pdf-long-detail-mobile.png', 'pdf-report-mobile.png'] }, null, 2));
  await testInfo.attach('pdf-interaction-measurements.json', { path: report, contentType: 'application/json' });
});

test('裁剪和扫描页保留可见原稿且不发送不可确认文字，后绘遮挡的内容不会泄露到阅读区或模型', async ({ pdf }, testInfo) => {
  const { driver, server } = pdf;
  await driver.command('file', [pdfLayoutFixture.toString('base64'), 'visibility-cases.pdf']);
  await expect.poll(async () => (await driver.snapshot()).source).toContain(pdfLayoutTexts.title);
  await driver.command('fill', ['#page-number', '2']); await driver.command('submit', ['#page-number']);
  await expect.poll(async () => (await driver.snapshot()).status).toContain('可见性无法确认');
  let state = await driver.snapshot(); expect(state.canvasVisible).toBe(true); expect(state.source).toHaveLength(0); expect(state.reading).toBe(false);
  expect(state.overlays).toHaveLength(0); expect((await driver.pixels()).changed).toBe(0);
  await driver.command('click', ['开启双语']); await driver.command('frame');
  expect(server.calls).toHaveLength(0);
  expect(await driver.command('button-enabled', ['阅读模式'])).toBe(false);
  state = await driver.snapshot(); expect(state.reading).toBe(false); expect(state.canvasVisible).toBe(true); expect(state.source).toHaveLength(0);
  await driver.screenshot(testInfo.outputPath('pdf-clipping-original.png'));
  await driver.command('fill', ['#page-number', '3']); await driver.command('submit', ['#page-number']);
  await expect.poll(async () => (await driver.snapshot()).status).toContain('暂不支持 OCR');
  state = await driver.snapshot(); expect(state.reading).toBe(false); expect(state.canvasVisible).toBe(true); expect(state.source).toHaveLength(0);
  expect(state.translations).toHaveLength(0); expect(server.calls).toHaveLength(0);
  const scan = await driver.pixels(); expect(scan.changed).toBe(0); expect(scan.nonWhite).toBeGreaterThan(1000);
  await driver.screenshot(testInfo.outputPath('pdf-scan-original.png'));
  await driver.command('click', ['页面对照']);
  await driver.command('fill', ['#page-number', '4']); await driver.command('submit', ['#page-number']);
  await expect.poll(async () => (await driver.snapshot()).status).toContain('本页翻译完成');
  state = await driver.snapshot(); expect(state.source).toEqual([pdfLayoutTexts.visible]);
  expect(state.translations.join('')).toContain('可见页面摘要');
  expect(server.calls.flatMap(call => call.texts ?? [])).toEqual([pdfLayoutTexts.visible]);
  expect(JSON.stringify(state)).not.toContain(pdfLayoutTexts.concealed);
  const redacted = await driver.pixels([{ name: 'covered-text', x: 40, y: 112, width: 520, height: 45 }]);
  expect(redacted.probes[0]).toMatchObject({ changed: 0, nonWhite: 0 }); expect(redacted.outsideOverlays).toBe(0);
  await driver.screenshot(testInfo.outputPath('pdf-covered-text.png'));
});
