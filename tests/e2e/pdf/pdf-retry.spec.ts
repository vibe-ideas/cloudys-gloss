import { test, expect } from './pdf-browser';
import { createPdfFixture } from './pdf-fixture';

test('PDF 服务失败时显示具体 HTTP 原因，单段重试独立恢复，重新翻译失败保留上次译文', async ({ pdf }, testInfo) => {
  const { driver, server } = pdf;
  await driver.command('file', [createPdfFixture(1).toString('base64'), 'retry.pdf']);
  await expect.poll(async () => (await driver.snapshot()).source.length).toBe(3);
  server.setTranslationFailure(503);
  await driver.command('click', ['开启双语']);
  await expect.poll(async () => (await driver.snapshot()).errors.length).toBe(3);
  expect((await driver.pixels()).changed).toBe(0);
  await driver.command('open-block', ['0']);
  await expect.poll(async () => (await driver.snapshot()).dialog.error).toContain('HTTP 503');
  await driver.screenshot(testInfo.outputPath('pdf-error-reason.png'));
  const before = server.calls.length;
  server.setTranslationFailure(0);
  await driver.command('click', ['重试这一段']);
  await expect.poll(async () => (await driver.snapshot()).dialog.translation).toContain('中文');
  expect((await driver.snapshot()).errors).toHaveLength(2);
  expect(server.calls.slice(before).map(call => call.texts)).toEqual([['Reading page 1']]);
  const previous = (await driver.snapshot()).dialog.translation;
  expect(previous).toContain('中文');
  server.setTranslationFailure(429);
  await driver.command('click', ['重新翻译这一段']);
  await expect.poll(async () => (await driver.snapshot()).dialog.error).toContain('HTTP 429');
  expect((await driver.snapshot()).dialog.translation).toBe(previous);
  server.setTranslationFailure(0); server.setTranslation('Reading page 1', '重新翻译后的第 1 页'); server.holdStreams();
  const last = server.calls.length;
  await driver.command('click', ['重试这一段']);
  await expect.poll(() => server.calls.length).toBe(last + 1);
  expect(await driver.command('button-enabled', ['正在重试…'])).toBe(false);
  expect((await driver.snapshot()).dialog.translation).toBe(previous);
  server.releaseStreams();
  await expect.poll(async () => (await driver.snapshot()).dialog.translation).toBe('重新翻译后的第 1 页');
  expect((await driver.snapshot()).dialog.error).toBe('');
  expect((await driver.snapshot()).errors).toHaveLength(2);
  expect(server.calls.slice(last).map(call => call.texts)).toEqual([['Reading page 1']]);
});

test('PDF 数值校验失败说明原因，阅读模式重试只刷新错误段缓存，不重译其他段落', async ({ pdf }) => {
  const { driver, server } = pdf;
  await driver.command('file', [createPdfFixture(1).toString('base64'), 'numbers.pdf']);
  await expect.poll(async () => (await driver.snapshot()).source.length).toBe(3);
  const source = (await driver.snapshot()).source[1]!;
  server.setTranslation(source, '第 999 页的内容编号发生了变化。');
  await driver.command('click', ['开启双语']);
  await expect.poll(async () => (await driver.snapshot()).errors.length).toBe(1);
  expect((await driver.snapshot()).errors[0]).toContain('数值与原文不一致');
  await driver.command('click', ['阅读模式']);
  await driver.command('click', ['查看错误原因']);
  await expect.poll(async () => (await driver.snapshot()).dialog.error).toContain('数值与原文不一致');
  await driver.command('click', ['关闭段落详情']);
  const before = server.calls.length;
  server.setTranslation(source, '第 1 页介绍语言如何连接人们，平静的布局让原文与译文保持相邻。');
  await driver.command('click', ['重新翻译第 2 段']);
  await expect.poll(async () => (await driver.snapshot()).errors.length).toBe(0);
  await expect.poll(async () => (await driver.snapshot()).translations).toContain('第 1 页介绍语言如何连接人们，平静的布局让原文与译文保持相邻。');
  expect(server.calls.slice(before).map(call => call.texts)).toEqual([[source]]);
  expect((await driver.snapshot()).translations).toHaveLength(3);
});

test('PDF 单段重新翻译期间切页取消旧请求，迟到结果不覆盖新页也不显示取消错误', async ({ pdf }) => {
  const { driver, server } = pdf;
  await driver.command('file', [createPdfFixture(2).toString('base64'), 'cancel-retry.pdf']);
  await expect.poll(async () => (await driver.snapshot()).source.length).toBe(3);
  await driver.command('click', ['开启双语']);
  await expect.poll(async () => (await driver.snapshot()).status).toContain('本页翻译完成');
  server.holdStreams();
  await driver.command('open-block', ['0']);
  const before = server.calls.length;
  await driver.command('click', ['重新翻译这一段']);
  await expect.poll(() => server.calls.length).toBe(before + 1);
  await driver.command('click', ['关闭段落详情']);
  await driver.command('click', ['下一页']);
  await expect.poll(() => server.abortedStreams).toBeGreaterThan(0);
  server.releaseStreams();
  await expect.poll(async () => (await driver.snapshot()).status).toContain('本页翻译完成');
  const state = await driver.snapshot();
  expect(state.page).toBe('2'); expect(state.errors).toHaveLength(0); expect(state.dialog.open).toBe(false);
  expect(state.source.join(' ')).toContain('Page 2'); expect(state.translations.join(' ')).not.toContain('page 1');
});

test('PDF 先单独翻译一段再开启整页双语，不取消单段请求且每段只翻译一次', async ({ pdf }) => {
  const { driver, server } = pdf;
  await driver.command('file', [createPdfFixture(1).toString('base64'), 'single-first.pdf']);
  await expect.poll(async () => (await driver.snapshot()).source.length).toBe(3);
  const source = (await driver.snapshot()).source;
  server.holdStreams();
  await driver.command('open-block', ['0']);
  await driver.command('click', ['翻译这一段']);
  await expect.poll(() => server.calls.length).toBe(1);
  await driver.command('click', ['关闭段落详情']);
  await driver.command('click', ['开启双语']);
  await driver.command('frame');
  server.releaseStreams();
  await expect.poll(async () => (await driver.snapshot()).status).toContain('本页翻译完成');
  expect(server.abortedStreams).toBe(0);
  expect(server.calls.flatMap(call => call.texts ?? []).sort()).toEqual([...source].sort());
  expect((await driver.snapshot()).errors).toHaveLength(0);
});
